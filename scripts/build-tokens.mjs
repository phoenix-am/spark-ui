// Generates packages/core/src/styles/tokens.css from the TypeScript themes,
// so the CSS variables and the JS theme can never drift apart.
import { build } from 'esbuild';
import { writeFileSync, mkdtempSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { pathToFileURL } from 'node:url';

const out = join(mkdtempSync(join(tmpdir(), 'spark-tokens-')), 'styles.mjs');
await build({
  entryPoints: ['packages/styles/src/index.ts'],
  bundle: true,
  format: 'esm',
  platform: 'node',
  outfile: out,
  external: ['@emotion/react'],
  logLevel: 'silent',
});
const { darkTheme, lightTheme, themeToCss } = await import(pathToFileURL(out).href);

const css = [
  '/* Generated by scripts/build-tokens.mjs. Do not edit; change packages/styles/src/theme.ts. */',
  themeToCss(darkTheme, ':root, [data-spark-theme="dark"]'),
  themeToCss(lightTheme, '[data-spark-theme="light"]'),
  '@media (prefers-color-scheme: light) {',
  themeToCss(lightTheme, '  [data-spark-theme="system"]').replace(/\n(?!$)/g, '\n  '),
  '}',
  themeToCss(darkTheme, '@media (prefers-color-scheme: dark) { [data-spark-theme="system"]').replace(/\}\n$/, '} }\n'),
].join('\n');
writeFileSync('packages/core/src/styles/tokens.css', css);
console.log('tokens.css written:', css.split('\n').length, 'lines');
