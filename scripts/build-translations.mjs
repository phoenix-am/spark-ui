// Writes docs/translations.md: every built-in UI label side by side
// (English, Hindi, Gujarati, Tamil) for native speakers to review.
// Run: npm run translations
import { build } from 'esbuild';
import { writeFileSync, mkdirSync, rmSync } from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

// Bundled inside the repo so `react` resolves from node_modules.
mkdirSync('node_modules/.cache', { recursive: true });
const out = path.resolve('node_modules/.cache/sparkwire-messages.mjs');
await build({
  entryPoints: ['packages/core/src/internal/messages.tsx'],
  bundle: true,
  format: 'esm',
  platform: 'node',
  outfile: out,
  external: ['react', 'react/jsx-runtime'],
  logLevel: 'silent',
});
const { builtInMessages } = await import(pathToFileURL(out).href);
rmSync(out);

const langs = [
  ['en', 'English'],
  ['hi', 'हिन्दी Hindi'],
  ['gu', 'ગુજરાતી Gujarati'],
  ['ta', 'தமிழ் Tamil'],
];
// Labels that take values show placeholders, e.g. "{1} selected".
const show = (v) => {
  if (typeof v === 'function') v = v(...Array.from({ length: Math.max(v.length, 1) }, (_, i) => `{${i + 1}}`));
  return String(v).replace(/\|/g, '\\|').replace(/\n/g, ' ');
};
const keys = Object.keys(builtInMessages.en).filter((k) => typeof builtInMessages.en[k] !== 'object');

let md = `# Translation review

Sparkwire ships its built-in labels (button names, screen-reader text, table and calendar text) in English, Hindi, Gujarati and Tamil. The Hindi, Gujarati and Tamil text has **not yet been reviewed by native speakers**. If you speak one of them, corrections are very welcome.

**How to help:** read down your language's column. If a label is wrong, unnatural, or too formal for an app, open an issue or a pull request that edits \`packages/core/src/internal/messages.tsx\`. \`{1}\`, \`{2}\` mark values filled in at runtime, such as a number or a column name; keep them in your version, in whatever order reads naturally.

Things worth checking:

- Words a screen reader speaks (e.g. "Next page", "Remove file") should sound natural when heard, not only when read.
- Short labels on buttons should stay short.
- Number and date formats come from the browser (\`Intl\`), so they don't need translating here.

_This file is generated by \`npm run translations\`; edit \`messages.tsx\`, not this file._

| Key | ${langs.map(([, n]) => n).join(' | ')} |
|---|${langs.map(() => '---').join('|')}|
`;
for (const k of keys) md += `| \`${k}\` | ${langs.map(([l]) => show(builtInMessages[l][k])).join(' | ')} |\n`;
writeFileSync('docs/translations.md', md);
console.log(`translations: ${keys.length} labels × ${langs.length} languages → docs/translations.md`);
